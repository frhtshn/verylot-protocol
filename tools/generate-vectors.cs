// Regenerates test-vectors/v1.json from the reference implementation:
//   dotnet run tools/generate-vectors.cs > test-vectors/v1.json
// Every input is derived from fixed labels, so the output is byte-for-byte reproducible.
// drand randomness here is synthetic (SHA-256 of a label), not a real beacon: these vectors test the
// derivation, not drand's BLS signatures.

using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using Verylot.Core;

static byte[] Label(string label) => SHA256.HashData(Encoding.ASCII.GetBytes($"verylot/test-vectors/v1/{label}"));
static string Hex(byte[] bytes) => Convert.ToHexStringLower(bytes);

var day = new DateOnly(2026, 10, 5);
var chain = SeedChain.FromRoot(day, Label("root"));
var first = SlotClock.FirstSlotOf(day);
var last = first + SlotClock.SlotsPerDay - 1;

byte[] DrandFor(long slot) => Label($"drand/{DrandChain.Quicknet.RoundForSlot(slot)}");

// A slot whose HMAC starts with a byte >= 250, so the digit comes from a later byte.
var skipSlot = first;
while (MacFor(skipSlot)[0] < 250) skipSlot++;

byte[] MacFor(long slot)
{
    // Same message as DigitDerivation with counter 0; recomputed here only to report the intermediate values.
    var tag = Encoding.ASCII.GetBytes("verylot/digit/v1");
    var drand = DrandFor(slot);
    var message = new byte[tag.Length + 12 + drand.Length];
    tag.CopyTo(message, 0);
    System.Buffers.Binary.BinaryPrimitives.WriteInt64BigEndian(message.AsSpan(tag.Length), slot);
    drand.CopyTo(message, tag.Length + 12);
    return HMACSHA256.HashData(chain.SeedForSlot(slot), message);
}

JsonObject Slot(long slot, string note) => new()
{
    ["note"] = note,
    ["slot"] = slot,
    ["time"] = SlotClock.ToTime(slot).ToString("yyyy-MM-dd'T'HH:mm:ss'Z'"),
    ["day"] = SlotClock.DayOf(slot).ToString("yyyy-MM-dd"),
    ["indexInDay"] = SlotClock.IndexInDay(slot),
    ["drandRound"] = DrandChain.Quicknet.RoundForSlot(slot),
};

JsonObject Digit(long slot, string note)
{
    var mac = MacFor(slot);
    var byteIndex = Array.FindIndex(mac, b => b < 250);
    var digit = DigitDerivation.Derive(chain.SeedForSlot(slot), slot, DrandFor(slot));
    if (digit != mac[byteIndex] % 10) throw new InvalidOperationException("Generator disagrees with DigitDerivation.");
    return new()
    {
        ["note"] = note,
        ["slot"] = slot,
        ["seed"] = Hex(chain.SeedForSlot(slot)),
        ["drandRandomness"] = Hex(DrandFor(slot)),
        ["mac"] = Hex(mac),
        ["byteIndex"] = byteIndex,
        ["byteValue"] = mac[byteIndex],
        ["digit"] = digit,
    };
}

JsonObject Check(byte[] seed, int index, byte[] commitment, bool valid, string note) => new()
{
    ["note"] = note,
    ["seed"] = Hex(seed),
    ["indexInDay"] = index,
    ["commitment"] = Hex(commitment),
    ["valid"] = valid,
};

var mid = first + 4321;
var vectors = new JsonObject
{
    ["protocol"] = "verylot/v1",
    ["about"] = "Generated by tools/generate-vectors.cs. drand randomness is synthetic; see SPEC.md.",
    ["slots"] = new JsonArray(
        Slot(first, "first slot of the UTC day"),
        Slot(mid, "middle of the day"),
        Slot(last, "last slot of the UTC day"),
        Slot(last + 1, "first slot of the next day")),
    ["chain"] = new JsonObject
    {
        ["day"] = day.ToString("yyyy-MM-dd"),
        ["root"] = Hex(chain.Root),
        ["commitment"] = Hex(chain.Commitment),
        ["seeds"] = new JsonArray(
            new JsonObject { ["indexInDay"] = 0, ["seed"] = Hex(chain.SeedForIndex(0)) },
            new JsonObject { ["indexInDay"] = 1, ["seed"] = Hex(chain.SeedForIndex(1)) },
            new JsonObject { ["indexInDay"] = 4321, ["seed"] = Hex(chain.SeedForIndex(4321)) },
            new JsonObject { ["indexInDay"] = 8639, ["seed"] = Hex(chain.SeedForIndex(8639)) }),
    },
    ["chainChecks"] = new JsonArray(
        Check(chain.SeedForIndex(0), 0, chain.Commitment, true, "first seed"),
        Check(chain.SeedForIndex(8639), 8639, chain.Commitment, true, "last seed (the root)"),
        Check(chain.SeedForIndex(4321), 4320, chain.Commitment, false, "right seed, wrong index"),
        Check(Label("not-a-seed"), 4321, chain.Commitment, false, "wrong seed"),
        Check(chain.SeedForIndex(4321), 4321, Label("not-a-commitment"), false, "wrong commitment")),
    ["digits"] = new JsonArray(
        Digit(first, "first slot of the day"),
        Digit(mid, "middle of the day"),
        Digit(last, "last slot of the day (seed = root)"),
        Digit(skipSlot, "first HMAC byte is >= 250, so a later byte is used")),
};

Console.Out.NewLine = "\n";
Console.WriteLine(vectors.ToJsonString(new JsonSerializerOptions { WriteIndented = true }));
